import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, phone: string) {
 await page.goto('/login')
 await page.locator('#phone').fill(phone)
 await page.locator('#phone').press('Enter')
 await expect(page.locator('#code')).toBeVisible()
 const otp=(await page.locator('.demo-hint b').textContent())?.trim()
 if(!otp) throw Error('Development OTP required; test DB only')
 await page.locator('#code').fill(otp)
 await page.locator('#code').press('Enter')
 await expect(page).toHaveURL(/\/dashboard/)
}
test('browser booking buttons, collision prevention, cancellation confirmation and released slot',async ({browser,request})=>{
 test.setTimeout(90000)
 const customer=await browser.newContext(), admin=await browser.newContext()
 try{
  const c=await customer.newPage()
  await login(c,'09120000981')
  await c.goto('/book')
  const submit=c.getByRole('button',{name:'ثبت درخواست نوبت'})
  await expect(submit).toBeDisabled()
  await c.getByRole('combobox',{name:'سالن'}).selectOption({label:'E2E Test Salon'})
  await c.getByRole('combobox',{name:'آرایشگر'}).selectOption({label:'E2E Barber'})
  await c.getByRole('combobox',{name:'خدمت'}).selectOption({label:'E2E Haircut'})
  const date=new Date(Date.now()+7*86400000).toISOString().slice(0,10)
  await c.getByLabel('تاریخ').fill(date)
  const slot=c.locator('.slot-grid button').first()
  await expect(slot).toBeVisible()
  const time=await slot.textContent()
  await slot.click()
  await expect(slot).toHaveClass(/selected/)
  await expect(submit).toBeEnabled()
  await submit.click()
  await expect(c.getByText('درخواست نوبت ثبت شد و در انتظار تأیید است')).toBeVisible()
  await expect(c.locator('.slot-grid button').filter({hasText:time?.trim() ?? ''})).toHaveCount(0)
  await expect(submit).toBeDisabled()

  const a=await admin.newPage()
  await login(a,'09120000983')
  await a.goto('/appointments')
  const pending=a.locator('.mgmt-card').filter({hasText:'E2E Customer'}).filter({hasText:'در انتظار تأیید'}).first()
  await expect(pending).toBeVisible()
  await a.getByRole('button',{name:'در انتظار تأیید'}).click()
  await expect(pending).toBeVisible()
  a.once('dialog',dialog=>dialog.dismiss())
  await pending.getByRole('button',{name:'لغو نوبت'}).click()
  await expect(pending).toBeVisible()
  a.once('dialog',dialog=>dialog.accept())
  await pending.getByRole('button',{name:'لغو نوبت'}).click()
  await expect(a.getByText('وضعیت نوبت به «لغو شده» تغییر کرد')).toBeVisible()
  await c.reload()
  await expect(c.getByText('لغو شده').first()).toBeVisible()
 }finally{await Promise.allSettled([customer.close(),admin.close()])}
})
